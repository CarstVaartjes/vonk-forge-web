#!/usr/bin/env node
// Generate web/src/api/catalog.generated.d.ts from the schema that ships in the
// verified recipe-library release (web/public/catalog/catalog-index-v2.schema.json,
// written by recipe-release.mjs). The adapter and the test fixtures read the index
// through these types, so `tsc` fails when either reads a field the contract does not have.
//
// The contract publishes documents without the fields they leave at their default
// (exclude_unset), so a property with a default is optional here, not required.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

export const SCHEMA_FILE = "catalog-index-v2.schema.json";

export async function generateCatalogTypes(schemaPath, outputPath) {
  const schema = JSON.parse(await readFile(schemaPath, "utf8"));
  const source = astToString(await openapiTS(schema, { defaultNonNullable: false }));
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, `// Generated by web/scripts/generate-catalog-types.mjs. Do not edit.\n${source}`);
}

async function main() {
  const webRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
  const output = path.join(webRoot, "src", "api", "catalog.generated.d.ts");
  await generateCatalogTypes(path.join(webRoot, "public", "catalog", SCHEMA_FILE), output);
  console.log(`Wrote ${path.relative(process.cwd(), output)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
